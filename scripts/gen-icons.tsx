const dir = "./public/icons/sf";
mkdirSync(dir, { recursive: true });
for (const [name, comp] of Object.entries(map)) {
  let svg = renderToStaticMarkup(createElement(I[comp] as any, { size: 24, strokeWidth: 1.9 }));
  svg = svg.replace(/var\(--icon-accent, currentColor\)/g, "#000").replace(/currentColor/g, "#000").replace(/ class="[^"]*"/, "").replace(/ aria-hidden="true"/, "");
  writeFileSync(`${dir}/${name}.svg`, svg);
}
const names = Object.keys(map);
const css = names.map((n) => `svg.tabler-icon-${n}`).join(",\n") + ` {\n  background-color: currentColor;\n  -webkit-mask: var(--sf-mask) center / contain no-repeat;\n  mask: var(--sf-mask) center / contain no-repeat;\n}\n` +
  names.map((n) => `svg.tabler-icon-${n}`).join(", ") + ` { & > * { display: none; } }\n` +
  names.map((n) => `svg.tabler-icon-${n} { --sf-mask: url("/icons/sf/${n}.svg"); }`).join("\n") + "\n";
writeFileSync("./app/components/icons/tabler-swap.css", "/* Generated by scripts/gen-icons.tsx: draws SignalForge glyphs over icons inside framework chat/settings UI. */\n" + css);
