  "arrow-up": "IconArrowUp", microphone: "IconMic", "voice-chat": "IconWaveform", "layout-sidebar-right": "IconLayoutSidebarRight",
  "player-stop": "IconStop", "player-stop-filled": "IconStop", check: "IconCheck", sparkles: "IconSparkles", history: "IconHistory",
